package ArrarList;

import java.util.*;

public class Array {
    public static void main(String[] arg) {
        int[] arr = {12, 15, 18};

        for (int i = 0; i < arr.length; i++) {
            System.out.println(arr[i]);
        }
        for(int val:arr){
            System.out.println(val);
        }
    }
}